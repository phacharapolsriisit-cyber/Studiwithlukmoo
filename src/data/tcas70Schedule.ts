// Helper to convert TCAS items to CalendarEvent
export function convertTCASToCalendarEvents(): CalendarEvent[] {
  return TCAS70_SCHEDULE_ITEMS.map((item) => ({
    id: item.id,
    title: item.title,
    type: item.type,
    date: item.date,
    endDate: item.endDate,
    rawDateThai: item.rawDateThai,
    priority: item.priority,
    isCompleted: false,
    notes: item.notes,
    isPinned: true,
    isOfficial: true,
    categoryTag: item.roundName,
    monthThai: item.monthThai,
    isNew: item.isNew,
    isExamHighlight: item.isExamHighlight,
    createdAt: '2026-08-10T00:00:00.000Z',
  }));
}

// Group items by month
export function getTCASGroupedByMonth() {
  const groups: { monthThai: string; items: TCASScheduleItem[] }[] = [];
  const monthOrder = [
    'ก.ค. 69',
    'ส.ค. 69',
    'ก.ย. 69',
    'พ.ย. 69',
    'ธ.ค. 69',
    'ม.ค. 70',
    'ก.พ. 70',
    'มี.ค. 70',
    'เม.ย. 70',
    'พ.ค. 70',
    'มิ.ย. 70',
  ];

  for (const m of monthOrder) {
    const items = TCAS70_SCHEDULE_ITEMS.filter((item) => item.monthThai === m);
    if (items.length > 0) {
      groups.push({ monthThai: m, items });
    }
  }

  return groups;
}
